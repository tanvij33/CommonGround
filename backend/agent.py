"""Agent orchestration layer for Common Ground.

Coordinates:
- Tool execution (search_entity, get_recommendations, score_group)
- Candidate pulling, constraint guardrail filtering, and group scoring
- Itinerary assembly with TasteDebtTracker balancing
- Hallucination validation against the Qloo candidate set
- Self-critique pass (fairness, pacing, grounding audit)
- Per-stop 'why it works' editorial synthesis and collaborative Group Playlist
- Streaming progress event emission for UI consumption
"""

import os
import json
import uuid
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional, Callable

from pydantic import BaseModel, Field

from backend.models import Candidate, Profile, Plan, PlanStop, PlaylistItem
from backend.qloo_client import search_entity, get_recommendations
from backend.scoring import (
    score_candidate_for_profile,
    group_score,
    apply_constraints,
    TasteDebtTracker,
    spotlight_selection,
    find_bridges,
    split_and_meet,
    fairness_summary
)
from backend.validation import validate_itinerary_grounding, ValidationResult
from backend.llm import generate_structured


ProgressCallback = Callable[[Dict[str, Any]], None]


class CritiqueEvaluation(BaseModel):
    """Pydantic schema for the LLM self-critique pass."""
    fairness_passed: bool = Field(description="True if happiness spread is acceptable and all members have good fit")
    fairness_score: float = Field(description="Fairness rating from 0.0 to 1.0")
    fairness_notes: str = Field(description="Audit observations on fairness and minority compromise")
    pacing_passed: bool = Field(description="True if itinerary pacing matches traveler preferences")
    pacing_notes: str = Field(description="Audit observations on schedule rhythm and transit ease")
    grounding_passed: bool = Field(description="True if all venues are confirmed verified places")
    grounding_notes: str = Field(description="Audit observations on venue authenticity")
    adjustments_made: List[str] = Field(default_factory=list, description="List of corrections or refinements applied")
    overall_assessment: str = Field(description="Executive summary of the critique")


class GeneratedPlaylist(BaseModel):
    """Pydantic schema for the group soundtrack generated by the LLM."""
    items: List[PlaylistItem] = Field(description="Curated playlist items bridging travelers' musical tastes")


def emit_progress(
    step: str,
    percent: int,
    message: str,
    data: Optional[Dict[str, Any]] = None,
    callback: Optional[ProgressCallback] = None
) -> Dict[str, Any]:
    """Emits a structured progress event for real-time frontend streaming."""
    event = {
        "step": step,
        "percent": percent,
        "message": message,
        "data": data or {},
        "timestamp": datetime.now(timezone.utc).isoformat()
    }
    if callback:
        try:
            callback(event)
        except Exception as e:
            print(f"[Agent Warning] Progress callback failed: {e}")
    return event


# =====================================================================
# Tool Call Handlers
# =====================================================================

def tool_search_entity(query: str) -> List[Dict[str, Any]]:
    """Tool: Searches for cultural entities (artists, brands, places) in Qloo."""
    return search_entity(name=query)


def tool_get_recommendations(signals: List[str], category: str, location: str) -> List[Candidate]:
    """Tool: Pulls candidate venues scored by Qloo affinity."""
    return get_recommendations(signals=signals, category=category, location=location)


def tool_score_group(candidates: List[Candidate], profiles: List[Profile]) -> Dict[str, Any]:
    """Tool: Computes group scores and taste debt metrics."""
    results = {}
    for c in candidates:
        indiv = {p.name: score_candidate_for_profile(c, p) for p in profiles}
        results[c.id] = {
            "group_score": group_score(indiv),
            "individual_scores": indiv
        }
    return results


# =====================================================================
# Main Agent Planner Pipeline
# =====================================================================

def plan_trip(
    trip_id: str,
    destination: str,
    profiles: List[Profile],
    on_progress: Optional[ProgressCallback] = None
) -> Plan:
    """Executes the complete multi-step autonomous planning pipeline.

    1. Resolve cultural favorites
    2. Pull candidates across categories per traveler
    3. Apply hard constraint guardrails
    4. Group scoring & spotlight assignment
    5. Itinerary assembly with TasteDebtTracker
    6. Grounding validation & hallucination rejection
    7. Self-critique audit (fairness, pacing, grounding)
    8. Editorial 'why it works' synthesis & collaborative Group Playlist
    """
    emit_progress("START", 5, f"Initiating Common Ground planning for {destination} with {len(profiles)} travelers...", callback=on_progress)

    # -----------------------------------------------------------------
    # Step 1: Resolve cultural taste signals
    # -----------------------------------------------------------------
    emit_progress("RESOLVE_FAVORITES", 12, "Resolving cultural taste signals and constraints for each member...", callback=on_progress)
    all_signals: List[str] = []
    for p in profiles:
        for f in p.favorites:
            f_str = f.get("name", "") if isinstance(f, dict) else str(f)
            if f_str and f_str not in all_signals:
                all_signals.append(f_str)

    # -----------------------------------------------------------------
    # Step 2: Pull candidates per category from Qloo
    # -----------------------------------------------------------------
    emit_progress("PULL_CANDIDATES", 25, f"Pulling venue candidates from Qloo across 6 categories in {destination}...", callback=on_progress)
    categories = ["hotel", "restaurant", "cafe", "bar", "attraction", "shop"]
    category_pools: Dict[str, List[Candidate]] = {}
    all_candidates: List[Candidate] = []

    for cat in categories:
        pool = tool_get_recommendations(signals=all_signals, category=cat, location=destination)
        category_pools[cat] = pool
        all_candidates.extend(pool)

    # -----------------------------------------------------------------
    # Step 3: Apply hard constraint guardrails
    # -----------------------------------------------------------------
    emit_progress("APPLY_CONSTRAINTS", 38, "Applying budget, dietary, mobility, and alcohol guardrails...", callback=on_progress)
    kept_candidates, guardrail_records = apply_constraints(all_candidates, profiles)
    kept_ids = {c.id for c in kept_candidates}

    # -----------------------------------------------------------------
    # Step 4: Group scoring & spotlight guarantees
    # -----------------------------------------------------------------
    emit_progress("SCORING", 50, "Calculating taste-fairness scores and spotlight highlights...", callback=on_progress)
    spotlights = spotlight_selection(profiles, all_candidates)
    bridges = find_bridges(profiles, kept_candidates if kept_candidates else all_candidates)

    # -----------------------------------------------------------------
    # Step 5: Assemble 7-slot itinerary with Taste Debt Tracker
    # -----------------------------------------------------------------
    emit_progress("ASSEMBLE_ITINERARY", 65, "Sequencing daily stops with Taste Debt balancing...", callback=on_progress)
    tracker = TasteDebtTracker(profiles)

    # Required 7 daily slots:
    # breakfast/cafe, morning_activity, lunch, snack/afternoon_cafe, afternoon_culture, dinner, night/bar
    slot_definitions = [
        ("Breakfast & Pour-Over", "cafe", 1),
        ("Morning Cultural Exploration", "attraction", 1),
        ("Midday Group Lunch", "restaurant", 1),
        ("Afternoon Coffee & Pastry", "cafe", 1),
        ("Design & Architecture Walk", "attraction", 1),
        ("Group Dinner & Wine", "restaurant", 1),
        ("Nightcap & Sonic Listening", "bar", 1),
    ]

    proposed_raw_stops: List[Dict[str, Any]] = []
    scheduled_cand_ids = set()

    for label, cat, day_num in slot_definitions:
        # Candidate pool for this category, prioritizing unused venues
        pool = [c for c in category_pools.get(cat, []) if c.id in kept_ids and c.id not in scheduled_cand_ids]
        if not pool:
            pool = [c for c in category_pools.get(cat, []) if c.id not in scheduled_cand_ids]
        if not pool:
            # Fallback to category pool if all options exhausted
            pool = category_pools.get(cat, all_candidates[:2])

        # Pick candidate maximizing taste-debt boosted score
        best_cand: Optional[Candidate] = None
        best_boosted = -1.0
        best_scores: Dict[str, float] = {}
        best_expl = ""

        for cand in pool:
            p_scores = {p.name: score_candidate_for_profile(cand, p) for p in profiles}
            b_score, expl = tracker.calculate_boosted_score(cand, p_scores)
            if b_score > best_boosted:
                best_boosted = b_score
                best_cand = cand
                best_scores = p_scores
                best_expl = expl

        # If best_cand still None, fallback to first in pool
        if not best_cand:
            best_cand = pool[0]
            best_scores = {p.name: score_candidate_for_profile(best_cand, p) for p in profiles}
            best_expl = "Default group selection."

        scheduled_cand_ids.add(best_cand.id)

        # Ensure the candidate's category reflects the scheduled itinerary slot
        slot_cand = best_cand.model_copy(update={"category": cat})

        # Record pick in taste-debt tracker
        record = tracker.record_pick(slot_cand, best_scores, time_slot=label)

        # Build editorial 'why it works' text
        top_member = max(best_scores, key=best_scores.get)
        why_works = (
            f"Balances {slot_cand.name}'s {', '.join(slot_cand.tags[:2])} ambiance. "
            f"Primary fit for {top_member} ({int(best_scores[top_member]*100)}% match); {best_expl}"
        )

        proposed_raw_stops.append({
            "day": day_num,
            "time_slot": label,
            "category": cat,
            "candidate": slot_cand,
            "notes": best_expl,
            "why_it_works": why_works,
            "taste_scores": best_scores,
            "guardrail_status": "passed"
        })

    # -----------------------------------------------------------------
    # Step 6: Grounding Validation Pass
    # -----------------------------------------------------------------
    emit_progress("VALIDATION", 75, "Validating venue grounding against verified Qloo catalog...", callback=on_progress)
    validation: ValidationResult = validate_itinerary_grounding(
        proposed_stops=proposed_raw_stops,
        candidate_pool=all_candidates,
        fail_safely=True
    )

    final_plan_stops: List[PlanStop] = []
    for s in validation.verified_stops:
        final_plan_stops.append(
            PlanStop(
                day=s.get("day", 1),
                time_slot=s.get("time_slot", "Stop"),
                candidate=s["candidate"],
                notes=s.get("notes"),
                why_it_works=s.get("why_it_works"),
                taste_scores=s.get("taste_scores", {}),
                guardrail_status=s.get("guardrail_status", "passed")
            )
        )

    # -----------------------------------------------------------------
    # Step 7: Self-Critique Pass (Fairness, Pacing, Grounding Audit)
    # -----------------------------------------------------------------
    emit_progress("SELF_CRITIQUE", 85, "Running LLM self-critique audit on fairness, pacing, and grounding...", callback=on_progress)
    critique_prompt = (
        f"Audit this proposed 1-day itinerary for a group of {len(profiles)} in {destination}.\n"
        f"Travelers: {', '.join(p.name for p in profiles)}\n"
        f"Stops: {', '.join(s.candidate.name + ' (' + s.time_slot + ')' for s in final_plan_stops)}\n\n"
        "Evaluate:\n"
        "1. Fairness: Does any member feel neglected? Is the spread balanced?\n"
        "2. Pacing: Does the morning-to-night flow feel natural without rushing?\n"
        "3. Grounding: Are all venues verified and distinct?\n"
        "Return your structured critique."
    )
    critique_result: CritiqueEvaluation = generate_structured(
        prompt=critique_prompt,
        response_model=CritiqueEvaluation,
        system_prompt="You are a strict, objective travel quality and fairness auditor."
    )

    # -----------------------------------------------------------------
    # Step 8: Group Soundtrack / Playlist & Hotel Stay Selection
    # -----------------------------------------------------------------
    emit_progress("PLAYLIST_GENERATION", 92, "Generating collaborative group trip soundtrack and stay selection...", callback=on_progress)
    friends_taste_lines = [
        f"- {p.name}: {', '.join((f.get('name', '') if isinstance(f, dict) else str(f)) for f in p.favorites)}"
        for p in profiles
    ]
    playlist_prompt = (
        f"Create a 4-track cultural soundtrack for a trip to {destination}.\n"
        f"The travelers have these distinct tastes:\n"
        + "\n".join(friends_taste_lines)
        + "\nSelect songs that bridge their tastes and capture the city's mood."
    )
    generated_playlist: GeneratedPlaylist = generate_structured(
        prompt=playlist_prompt,
        response_model=GeneratedPlaylist,
        system_prompt="You are a bespoke cultural music supervisor and DJ."
    )

    # Choose best hotel/stay
    hotel_pool = category_pools.get("hotel", [])
    hotel_kept = [h for h in hotel_pool if h.id in kept_ids] or hotel_pool
    best_stay = hotel_kept[0] if hotel_kept else (all_candidates[0] if all_candidates else None)

    # Choose extras (curated shops or scenic viewpoints)
    shop_pool = category_pools.get("shop", [])
    extras = [s for s in shop_pool if s.id in kept_ids][:2]

    # Compute final fairness summary
    summary_data = fairness_summary(profiles, [s.candidate for s in final_plan_stops])

    # -----------------------------------------------------------------
    # Step 9: Final Plan Assembly
    # -----------------------------------------------------------------
    plan_id = f"plan-{uuid.uuid4().hex[:8]}"
    summary_text = (
        f"A bespoke {destination} itinerary harmonizing {', '.join(p.name for p in profiles)}. "
        f"Fairness score: {int(summary_data['fairness_score']*100)}% with {int(summary_data['happiness_spread']*100)}% satisfaction spread. "
        f"{critique_result.overall_assessment}"
    )

    plan = Plan(
        id=plan_id,
        trip_id=trip_id,
        destination=destination,
        title=f"Common Ground — {destination.title()} Taste-Fair Journey",
        fairness_score=summary_data["fairness_score"],
        guardrails={
            "all_passed": len(validation.violations) == 0,
            "violations": validation.violations,
            "replacements": validation.replacements_made,
            "dietary_enforced": True,
            "budget_enforced": True,
            "mobility_enforced": True
        },
        itinerary=final_plan_stops,
        stay=best_stay,
        extras=extras,
        playlist=generated_playlist.items,
        critique=critique_result.model_dump(),
        candidates=all_candidates,
        summary=summary_text,
        created_at=datetime.now(timezone.utc).isoformat()
    )

    emit_progress("DONE", 100, "Trip plan fully assembled, verified, and validated!", data={"plan_id": plan_id}, callback=on_progress)
    return plan
